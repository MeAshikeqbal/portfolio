/**
 * Signs the footer's identity statement with the PGP key in siteConfig.pgpFingerprint and
 * writes lib/pgp.generated.ts (public key, key facts, clearsigned statement).
 *
 *   npx sanity exec scripts/sign-identity.ts
 *
 * Runs on your machine: it needs the secret key in your gpg keyring, and gpg asks for the
 * passphrase itself. Re-run after changing the name, tagline or links (lib/identity.ts), or after
 * extending the key's expiry; the unit tests fail until the signed copy matches.
 */
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import path from "node:path"
import { identityText } from "../lib/identity"
import { siteConfig } from "../lib/site"

const fingerprint = siteConfig.pgpFingerprint

function gpg(args: string[], input?: string): string {
  return execFileSync("gpg", args, { input, encoding: "utf8", stdio: ["pipe", "pipe", "inherit"] })
}

// Key facts from gpg's machine-readable listing (doc/DETAILS in the GnuPG sources).
const pub = gpg(["--with-colons", "--fixed-list-mode", "--list-keys", fingerprint])
  .split("\n")
  .find((line) => line.startsWith("pub:"))
  ?.split(":")
if (!pub) throw new Error(`Key ${fingerprint} is not in your keyring.`)

const epoch = (field: string | undefined) =>
  field ? new Date(Number(field) * 1000).toISOString() : null
const algorithms: Record<string, string> = { "1": "rsa", "19": "ecdsa", "22": "eddsa" }
// Field 17 names the curve for ECC keys ("ed25519"); RSA keys report their size in field 3.
const algorithm = pub[16] || `${algorithms[pub[3]] ?? "key"}${pub[3] === "1" ? pub[2] : ""}`

const publicKey = gpg(["--armor", "--export-options", "export-minimal", "--export", fingerprint])
const signedIdentity = gpg(
  ["--clearsign", "--digest-algo", "SHA512", "--local-user", `${fingerprint}!`],
  identityText(),
)

const out = path.join(process.cwd(), "lib/pgp.generated.ts")
writeFileSync(
  out,
  `// Generated by scripts/sign-identity.ts. Do not edit: change lib/identity.ts and re-run it.

export const pgpKey = {
  fingerprint: ${JSON.stringify(fingerprint)},
  algorithm: ${JSON.stringify(algorithm)},
  createdAt: ${JSON.stringify(epoch(pub[5]))},
  expiresAt: ${JSON.stringify(epoch(pub[6]))} as string | null,
  publicKey: ${JSON.stringify(publicKey)},
} as const

/** The identity statement, clearsigned. Served at /identity.asc and shown in the footer. */
export const signedIdentity = ${JSON.stringify(signedIdentity)}
`,
)
console.log(`Signed with ${fingerprint}; wrote ${path.relative(process.cwd(), out)}`)
